    private static RolePermission Create(string roleName, string permissionName)
    {
        var role = RoleSeed.Data.SingleOrDefault(x =>
            string.Equals(x.Name, roleName, StringComparison.Ordinal));

        var permission = PermissionSeed.Data.SingleOrDefault(x =>
            string.Equals(x.Name, permissionName, StringComparison.Ordinal));

        if (role is null)
        {
            throw new InvalidOperationException($"Seed role '{roleName}' was not found.");
        }

        if (permission is null)
        {
            throw new InvalidOperationException($"Seed permission '{permissionName}' was not found.");
        }

        return new RolePermission
        {
            RoleId = role.Id,
            PermissionId = permission.Id
        };
    }
